"""Isolated native->WSL provisioning smoke; requires explicit --provision-wsl.

Uses a dedicated NEW distro and an empty local schema, never real cloud data.
Leaves diagnostics and new test clusters in place; never unregisters/deletes WSL.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys


def run(args):
    sys.stdout.reconfigure(encoding='utf-8')
    package, scratch = args.package.resolve(), args.scratch.resolve()
    if scratch.exists() and not args.resume:
        raise RuntimeError('Use a NEW scratch directory. Nothing will be deleted.')
    if args.resume and (not (scratch / 'result.json').is_file() or (scratch / 'business/config.json').exists()):
        raise RuntimeError('Resume requires an earlier test result and NO business configuration.')
    scratch.mkdir(parents=True, exist_ok=args.resume)
    python = package / 'python/python.exe'
    env = {k: v for k, v in os.environ.items() if not k.startswith(('NOVA_', 'PG', 'PYTHON'))
           and k not in {'DJANGO_SETTINGS_MODULE', 'DATABASE_URL', 'RUN_MAIN'}}
    env['PYTHONUTF8'] = '1'
    # All installer state lives in this explicit fixture, not current-user
    # AppData. Real cloud/connection/locator files are never read or written.
    code = '''
from pathlib import Path
from unittest.mock import patch
import json,os,sys
sys.stdout.reconfigure(encoding='utf-8')
sys.stderr.reconfigure(encoding='utf-8')
from windows_installer import engines,wsl_setup
from local_pos.integrated_prepare import prepare
from local_pos.runtime import Postgres,installation_lock,port_free
from local_pos.wsl_postgres import WslPostgres,wait_for_forwarding_release
from local_pos.integrated_activation import backup_local
import psycopg2
project=Path.cwd()
scratch=Path(%r)
simulate_native_block=%r
path=scratch/'business/config.json'
def report(message,**values): print(message,values,flush=True)
original_probe=engines.probe
def test_probe(*args,**kwargs):
    if simulate_native_block and not kwargs.get('distribution'):
        print('TEST ONLY: injecting NativePolicyBlocked; no Windows policy changed',flush=True)
        raise engines.NativePolicyBlocked('SIMULATED 4551 for isolated fallback test')
    return original_probe(*args,port=55469,**kwargs)
with patch.object(engines,'connection_path',return_value=scratch/'private/connection.dpapi'), patch.object(engines,'probe',side_effect=test_probe):
    selected=engines.choose(project,path,project.parent/'postgresql/bin',report)
    if selected is None:
        engines.prepare_wsl(project,path,{'wsl_consent':True},report)
        selected=engines.choose(project,path,project.parent/'postgresql/bin',report)
    if not selected:
        raise RuntimeError('Engine preparation did not finish.')
    is_wsl='wsl_distribution' in selected
    if simulate_native_block and not is_wsl: raise RuntimeError('Fallback was not exercised')
    print('PASS: selected '+('WSL after simulated native block' if simulate_native_block else 'WSL after native block' if is_wsl else 'native SQL probe')+'; persisted selection',flush=True)
    # The real application schema, generated by the bundled Windows Python,
    # contains no downloaded business rows and uses only the new Linux cluster.
    config=prepare(project,path,port=55469,**selected)
    for attempt in range(2):
        with installation_lock(path.parent):
            engine=(WslPostgres if is_wsl else Postgres)(path.parent,config['pg_bin'],config)
            engine.start()
            try:
                with psycopg2.connect(host='127.0.0.1',port=config['port'],dbname=config['database'],
                     user=config['user'],password=config['password'],connect_timeout=5) as conn:
                    with conn.cursor() as c:
                        c.execute('DO $$ BEGIN PERFORM 1; END $$')
                        c.execute('CREATE TABLE IF NOT EXISTS installer_persistence_probe (value integer)')
                        if attempt==0: c.execute('INSERT INTO installer_persistence_probe VALUES (42)')
                        c.execute('SELECT value FROM installer_persistence_probe')
                        assert c.fetchall()==[(42,)]
                        c.execute("SELECT count(*) FROM information_schema.tables WHERE table_schema='public'")
                        print('PASS: real schema SQL and persistence; tables:',c.fetchone()[0],flush=True)
                if attempt==0:
                    backup=backup_local(config,project.parent/'postgresql/bin')
                    print('PASS: backup verified with native clients; no native server DLL',flush=True)
            finally: engine.stop()
        wait_for_forwarding_release(config['port'])
    with patch.object(engines,'probe',side_effect=AssertionError('must not switch engine')):
        assert engines.choose(project,path,project.parent/'postgresql/bin',report)['instance_id']==config['instance_id']
    print('PASS: existing copy preserved; no fallback or reprobe after installation',flush=True)
    if is_wsl: print('TEST_DISTRIBUTION:',wsl_setup.distribution_name(project),flush=True)
''' % (str(scratch), args.simulate_native_block)
    suffix = '-resume' if args.resume else ''
    with (scratch / ('progress' + suffix + '.log')).open('x', encoding='utf-8') as log:
        result = subprocess.run([str(python), '-B', '-c', code], cwd=package / 'app', env=env,
            stdout=log, stderr=subprocess.STDOUT, text=True, encoding='utf-8',
            errors='replace', timeout=3600, creationflags=subprocess.CREATE_NO_WINDOW)
    output = (scratch / ('progress' + suffix + '.log')).read_text(encoding='utf-8')
    (scratch / ('result' + suffix + '.json')).write_text(json.dumps({'returncode': result.returncode, 'output': output},
        ensure_ascii=False, indent=2), encoding='utf-8')
    print(output, flush=True)
    return result.returncode


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--package', type=Path, required=True)
    parser.add_argument('--scratch', type=Path, required=True)
    parser.add_argument('--provision-wsl', action='store_true', required=True)
    parser.add_argument('--simulate-native-block', action='store_true', help='Explicitly simulate 4551 to test fallback on hosts where native works')
    parser.add_argument('--resume', action='store_true', help='Resume the SAME failed fixture only before a business config exists')
    sys.exit(run(parser.parse_args()))
